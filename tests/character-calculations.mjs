import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
import { abilityModifier, clampCurrentHitPointsToMaximum, initiativeBonus, importSheetAbility, newCharacterSheet, parseCharacterSheets, syncTurnStats, turnFromSheet } from '../src/utils/CharacterSheets.ts'
import { abilityKeys, applyCreation, characterCalculationIssues, characterFieldMode, characterFieldValue, enableCreation, patchCalculatedSheetStats, resetCreationOverrides, translatedCreationData, updateCharacterField, withWizardCatalog } from '../src/utils/PlayerCreation.ts'
import { spellProfile, spellRowState } from '../src/utils/Spellcasting.ts'
import { wizardWardMaximum } from '../src/utils/Wizard.ts'
import { parseCatalog, refreshCombatSheetAbilities, sheetWithCombatAbilities } from '../src/utils/Catalog.ts'

const json = (name) => JSON.parse(readFileSync(new URL(`../public/data/${name}.json`, import.meta.url), 'utf8'))
const data = { ...json('character-options'), ...json('character-equipment'), skills: json('character-rules').skills }
const create = (id = 'wizard', edition = '2014', extra = {}) => enableCreation({ ...newCharacterSheet(), name: 'Calcoli', characterClass: id, level: '5', ...Object.fromEntries(abilityKeys.map((key) => [key, '14'])), ...extra,
    playerDetails: { 'creation.class': id, 'rules.edition': edition, ...extra.playerDetails } }, data)
const edit = (sheet, key, value) => applyCreation(updateCharacterField(sheet, key, value), data)
const reopen = (sheet) => applyCreation(parseCharacterSheets(JSON.stringify([sheet]))[0], data)

for (const [score, expected] of [['1', -5], ['9', -1], ['10', 0], ['30', 10], ['', undefined], [' ', undefined], ['0', undefined], ['15.5', undefined], ['Infinity', undefined], ['abc', undefined]]) assert.equal(abilityModifier(score), expected)
let wizard = create()
assert.equal(wizard.playerDetails.proficiencyBonus, '3')
assert.equal(wizard.playerDetails.maxHitPoints, '32')
assert.equal(wizard.playerDetails.spellDC, '13')
assert.equal(wizard.playerDetails.spellAttackBonus, '5')
assert.equal(edit(wizard, 'castingAbility', 'INT.').playerDetails.spellDC, '13')
assert.equal(wizard.playerDetails.unarmoredAC, '12')
assert.equal(wizard.playerDetails.unshieldedAC, '12')
assert.equal(wizard.playerDetails.maximumWeight, '105')
assert.equal(characterFieldMode(wizard, 'initiative'), 'manual', 'A rolled initiative is encounter state')
assert.equal(characterFieldMode(wizard, 'hitPoints'), 'manual', 'Current HP is not a derived maximum')
assert.equal(characterFieldMode(wizard, 'spellDC'), 'overridable')
assert.equal(characterFieldMode(wizard, 'inventory.0.3'), 'automatic')
assert.equal(characterFieldMode(wizard, 'modifier.intelligence'), 'automatic')
assert.equal(characterFieldValue(wizard, 'modifier.intelligence'), '+2')

wizard = edit(wizard, 'proficiencyBonus', '5')
assert.equal(wizard.playerDetails['save.intelligence'], '7')
assert.equal(wizard.playerDetails.spellDC, '15')
assert.equal(wizard.playerDetails.spellAttackBonus, '7')
wizard = edit(wizard, 'skill.Percezione.proficient', 'true')
wizard = edit(wizard, 'skill.Percezione.expertise', 'true')
assert.equal(wizard.playerDetails['skill.Percezione'], '12')
assert.equal(wizard.playerDetails.passivePerception, '22')
wizard = edit(wizard, 'skill.Percezione', '0')
assert.equal(wizard.playerDetails.passivePerception, '10', 'A manual zero must update its dependents')
wizard = edit(wizard, 'proficiencyBonus', '0')
assert.equal(wizard.playerDetails['save.intelligence'], '2')
assert.equal(wizard.playerDetails.spellDC, '10')
wizard = edit(wizard, 'castingAbility', 'Carisma')
wizard = edit(wizard, 'charisma', '20')
assert.equal(wizard.playerDetails.spellDC, '13')
assert.equal(spellProfile(wizard, data).preparedLimit, 10, 'The selected casting ability also controls 2014 preparation')
wizard = edit(wizard, 'spellDC', '0')
wizard = edit(wizard, 'level', '9')
assert.equal(wizard.playerDetails.spellDC, '0')
assert.equal(wizard.playerDetails.proficiencyBonus, '0')
assert.deepEqual(reopen(wizard), wizard)
assert.notEqual(resetCreationOverrides(wizard, data).playerDetails.spellDC, '0')
let typedMaximum = edit(create(), 'maxHitPoints', '9')
assert.equal(typedMaximum.hitPoints, '32', 'Typing an intermediate manual maximum must not prematurely discard HP')
typedMaximum = edit(typedMaximum, 'maxHitPoints', '99')
assert.equal(typedMaximum.hitPoints, '32', 'Typing a larger manual maximum must not heal the character')
assert.equal(clampCurrentHitPointsToMaximum(edit(typedMaximum, 'maxHitPoints', '20')).hitPoints, '20', 'The completed maximum clamps on blur/save')
assert.equal(patchCalculatedSheetStats(edit(typedMaximum, 'maxHitPoints', '20'), { hitPoints: '100' }, data).hitPoints, '20', 'Combat edits respect a manually configured maximum')

for (const edition of ['2014', '2024']) {
    const bard = create('bard', edition)
    assert.equal(initiativeBonus(bard), edition === '2014' ? '+3' : '+2')
    assert.equal(bard.playerDetails['skill.Arcano'], '3')
    const draconic = create('sorcerer', edition, { dexterity: '12', charisma: '18', playerDetails: { 'creation.subclass': 'draconic' } })
    assert.equal(draconic.armorClass, edition === '2014' ? '14' : '15')
    const low = edit(draconic, 'level', '1')
    assert.equal(low.playerDetails.maxHitPoints, edition === '2014' ? '9' : '8')
    assert.equal(low.armorClass, edition === '2014' ? '14' : '11', '2024 subclass features start at level 3')
    const elf = create('wizard', edition, { playerDetails: { 'creation.race': 'elf', 'creation.subrace': 'high-elf' } })
    assert.equal(elf.dexterity, edition === '2014' ? '16' : '14')
    assert.equal(elf.intelligence, edition === '2014' ? '15' : '14')
}

const armored = create('fighter', '2014', { dexterity: '', playerDetails: { 'choice.class.fighter.equipment.0.0': '0', 'creation.armor': 'chain-mail' } })
assert.equal(armored.armorClass, '16', 'Heavy armor needs no Dexterity score')
assert.equal(armored.playerDetails.unshieldedAC, '16')
assert.equal(armored.playerDetails.unarmoredAC, '')
let armed = edit(create(), 'attacks.0.0', 'crossbow-light')
assert.equal(armed.playerDetails['attacks.0.1'], '5', 'Plural weapon proficiency IDs must match light crossbows')
armed = edit(armed, 'proficiency.Armi semplici', 'true')
armed = edit(armed, 'attacks.0.0', 'Spear')
assert.equal(armed.playerDetails['attacks.0.1'], '5', 'Manual proficiency flags affect weapon attacks')
armed = edit(armed, 'attacks.0.0', 'Arma del DM')
assert.equal(armed.playerDetails['attacks.0.1'], '', 'Unknown weapons must not retain another weapon’s automatic bonus')

let inventory = edit(create(), 'inventory.0.1', '0,1')
inventory = edit(inventory, 'inventory.0.2', '3')
inventory = edit(inventory, 'inventory.1.1', '1.25')
assert.equal(inventory.playerDetails['inventory.0.3'], '0.3')
assert.equal(inventory.playerDetails.carriedWeight, '1.55')
inventory = edit(inventory, 'inventory.0.2', '0')
assert.equal(inventory.playerDetails['inventory.0.3'], '0')
assert.equal(inventory.playerDetails.carriedWeight, '1.25')
inventory = edit(inventory, 'inventory.1.1', '0')
assert.equal(inventory.playerDetails.carriedWeight, '0')
inventory = edit(inventory, 'coins.MO', '50')
assert.equal(inventory.playerDetails.carriedWeight, '0.5', 'Include the weight of recorded coins once')
inventory = edit(inventory, 'coins.MO', '0')
assert.equal(inventory.playerDetails.carriedWeight, '0')
assert.equal(characterFieldValue(inventory, 'inventory.0.3'), '0')
assert.equal(edit(inventory, 'inventory.0.3', '500').playerDetails['inventory.0.3'], '0', 'Read-only fields cannot become manual overrides')
inventory = edit(inventory, 'inventory.2.0', 'Peso sconosciuto')
assert.equal(inventory.playerDetails.carriedWeight, '', 'An incomplete inventory cannot claim a complete total')
inventory = edit(inventory, 'carriedWeight', '25.5')
inventory = edit(inventory, 'inventory.2.1', 'abc')
assert.equal(inventory.playerDetails.carriedWeight, '25.5', 'Keep explicitly overridden aggregate weights')
assert.ok(characterCalculationIssues(inventory).length)

for (const invalid of ['', ' ', 'oops', '15.5', 'Infinity', '0']) {
    const incomplete = edit(create(), 'intelligence', invalid)
    assert.equal(incomplete.playerDetails.spellDC, '')
    assert.equal(incomplete.playerDetails['save.intelligence'], '')
    assert.ok(!Object.values(incomplete.playerDetails).includes('NaN'))
}
const invalidLevel = edit(create(), 'level', '2.5')
assert.equal(invalidLevel.playerDetails.proficiencyBonus, '')
assert.equal(invalidLevel.playerDetails.maxHitPoints, '')
assert.equal(invalidLevel.playerDetails['slots.1.total'], '0')
assert.ok(characterCalculationIssues(invalidLevel).length)
const overSpent = edit(create(), 'slots.1.used', '5')
assert.ok(characterCalculationIssues(overSpent).some((issue) => issue.includes('slot spesi')))
const extraSlot = edit(create(), 'slots.9.total', '1')
assert.equal(spellRowState({ ...extraSlot, playerDetails: { ...extraSlot.playerDetails, 'spell.9.0.name': 'Wish', 'spell.9.0.prepared': 'true' } }, 9, 0).available, false, 'Custom slots do not grant knowledge of spells beyond the class level')
assert.equal(patchCalculatedSheetStats(create(), { hitPoints: '-1' }, data), null)
assert.ok(characterCalculationIssues({ ...create(), hitPoints: '-1' }).length)

const wizardData = withWizardCatalog(data, json('wizard-catalog'))
let ward = enableCreation({ ...create(), playerDetails: { ...create().playerDetails, 'creation.subclass': 'wizard-abjuration', 'wizard.ward.current': '100' } }, wizardData)
assert.equal(wizardWardMaximum(ward), 12)
assert.equal(ward.playerDetails['wizard.ward.current'], '12')
ward = applyCreation(updateCharacterField(ward, 'intelligence', '10'), wizardData)
assert.equal(ward.playerDetails['wizard.ward.max'], '10')
assert.equal(ward.playerDetails['wizard.ward.current'], '10', 'A lower ward maximum must refresh its remaining HP')
const lore = enableCreation({ ...create(), dexterity: '', playerDetails: { ...create().playerDetails, 'creation.base.dexterity': '', 'creation.subclass': 'wizard-lore-mastery-ua', 'wizard.initiativeAbility': 'intelligence' } }, wizardData)
assert.equal(initiativeBonus(lore), '+2', 'Intelligence replacing Dexterity must not require a Dexterity score')
let manualExpertise = edit(create(), 'skill.Arcano.proficient', 'true')
manualExpertise = edit(manualExpertise, 'skill.Arcano.expertise', 'true')
manualExpertise = applyCreation(updateCharacterField(manualExpertise, 'creation.subclass', 'wizard-lore-mastery-ua'), wizardData)
manualExpertise = applyCreation(updateCharacterField(manualExpertise, 'creation.subclass', ''), wizardData)
assert.equal(manualExpertise.playerDetails['skill.Arcano.expertise'], 'true', 'Manually chosen expertise survives a later automatic feature being added and removed')

let exhausted = edit(create('wizard', '2024'), 'exhaustion', '2')
assert.equal(exhausted.playerDetails['save.intelligence'], '1')
assert.equal(exhausted.playerDetails.spellAttackBonus, '1')
assert.equal(exhausted.playerDetails.spellDC, '13', 'Exhaustion affects tests, not spell DC')
assert.equal(exhausted.playerDetails['skill.Percezione'], '-2')
assert.equal(initiativeBonus(exhausted), '-2')
