let linked = patchCalculatedSheetStats(create(), { armorClass: '22', temporaryHitPoints: '7', hitPoints: '0', initiative: '17' }, data)
assert.equal(linked.playerDetails.temporaryHitPoints, '7', 'Editing AC and temporary HP together preserves both')
for (const template of ['generic', 'wizard', 'wizard-pdf']) {
    linked = edit(linked, 'sheet.template', template)
    linked = edit(linked, 'dexterity', '18')
    linked = reopen(linked)
    assert.equal(linked.armorClass, '22')
    assert.equal(linked.hitPoints, '0')
    assert.equal(linked.initiative, '17')
    assert.equal(linked.playerDetails.temporaryHitPoints, '7')
    assert.equal(linked.playerDetails.unarmoredAC, '14')
    assert.equal(initiativeBonus(linked), '+4')
    assert.deepEqual(applyCreation(linked, data), linked, 'Every template must share an idempotent calculation pipeline')
    const turn = syncTurnStats(turnFromSheet(linked, 1), linked)
    assert.equal(turn.sheet.playerDetails.spellDC, linked.playerDetails.spellDC)
    assert.equal(turn.armorClass, linked.armorClass)
    assert.equal(turn.hitPoints, linked.hitPoints)
}
const catalog = parseCatalog(json('database'))
assert.equal(translatedCreationData(data, catalog).spells.find((spell) => spell.index === 'shield').nameIt, 'Scudo', 'Shared calculations preserve the selected spell language')
const localizedLife = applyCreation(create('cleric', '2014', { playerDetails: { 'creation.subclass': 'life', 'spell.1.0.name': 'Bless', 'spell.1.0.prepared': 'true' } }), translatedCreationData(data, catalog))
assert.equal(spellRowState(localizedLife, 1, 0).source, 'always', 'Changing language must preserve always-prepared grants saved under an English name')
assert.equal(spellRowState(localizedLife, 1, 0).countsPrepared, false)
const spellSheet = create('wizard', '2014', { abilities: [{ name: 'Capacità manuale', duration: '1 minuto' }], playerDetails: { 'spell.1.0.name': 'Shield', 'spell.1.0.prepared': 'true', 'spell.1.1.name': 'Magic Missile', 'spell.1.1.prepared': 'false' } })
const combatSheet = sheetWithCombatAbilities(spellSheet, catalog)
const shieldIndex = combatSheet.abilities.findIndex((item) => item.name === 'Scudo')
assert.ok(shieldIndex >= 0)
const imported = importSheetAbility([], combatSheet, 1, shieldIndex, 50)
const swapped = { ...spellSheet, playerDetails: { ...spellSheet.playerDetails, 'spell.1.0.prepared': 'false', 'spell.1.1.prepared': 'true' } }
const refreshed = refreshCombatSheetAbilities(combatSheet, swapped, catalog)
assert.ok(!refreshed.availableAbilityIndexes.includes(shieldIndex), 'An unprepared spell must no longer be offered for a new import')
assert.equal(refreshed.sheet.abilities[shieldIndex].name, 'Scudo', 'Keep the index used by an already imported spell')
assert.equal(imported[0].sheetAbilityIndex, shieldIndex)
assert.equal(imported[0].id, 50)
assert.ok(refreshed.availableAbilityIndexes.some((index) => refreshed.sheet.abilities[index].name === 'Dardo Incantato'), 'Newly prepared spells appear in the combat card')
assert.ok(refreshed.availableAbilityIndexes.includes(0), 'Manual abilities remain available')
assert.ok(refreshCombatSheetAbilities(refreshed.sheet, spellSheet, catalog).availableAbilityIndexes.includes(shieldIndex), 'Preparing the spell again reuses its existing index')
console.log('Character calculations passed: editions, dependencies, overrides, blank/zero/decimal/invalid input, inventory, templates, persistence and combat')
