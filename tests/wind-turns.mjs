// node tests/wind-turns.mjs — rule timing and persisted outcomes, no live data.
import assert from 'node:assert/strict'
import {beginWindTurn,resolveAutomaticWindSaves,pendingWindSaves,resolveWindSave,windSaveResults,validWindSave} from '../src/domain/dnd/WindTurns.ts'
import {validateState} from '../server/games.mjs'
const wind={id:8,ruleId:'phb2014:spell:gust-of-wind',name:'Folata di Vento',ownerId:1,active:true,concentration:true,duration:'1 minuto',remainingTurns:9,windSave:{dc:19},targets:[{id:2,damage:'0',resolved:true}]}
let abilities=[structuredClone(wind)],combat={activeId:1,round:1}
assert.equal(pendingWindSaves(abilities,combat).length,0,'Casting does not require an immediate save')
abilities=beginWindTurn(abilities,combat)
abilities=abilities.map(a=>({...a,targets:[...a.targets,{id:1,damage:'0',resolved:true}]}))
assert.equal(pendingWindSaves(abilities,combat).length,0,'Entering or redirecting onto a creature during its turn does not trigger a save')
combat={activeId:2,round:1};abilities=beginWindTurn(abilities,combat)
assert.equal(pendingWindSaves(abilities,combat).length,1,'Starting inside triggers a save')
const snapshot=JSON.stringify(abilities)
abilities=resolveWindSave(abilities,combat,8,false)
assert.equal(pendingWindSaves(abilities,combat).length,0)
assert.equal(windSaveResults(abilities,combat)[0].windSave.turn.success,false)
assert(abilities[0].active&&abilities[0].concentration,'Failure does not end wind or concentration')
assert.equal(abilities[0].remainingTurns,9)
assert.deepEqual(abilities[0].targets,JSON.parse(snapshot)[0].targets,'The Master decides whether a pushed creature leaves the line')
assert.equal(resolveWindSave(abilities,combat,8,true),abilities,'A second click cannot overwrite a resolved save')
assert.deepEqual(beginWindTurn(abilities,combat),abilities,'Hydrating the same turn does not duplicate the save')
abilities=JSON.parse(JSON.stringify(abilities))
assert.equal(pendingWindSaves(abilities,combat).length,0,'A reload preserves the resolved turn')
combat={activeId:2,round:2};abilities=beginWindTurn(abilities,combat)
assert.equal(pendingWindSaves(abilities,combat).length,1,'Remaining in the line requires a new save next own turn')
abilities=resolveWindSave(abilities,combat,8,true)
assert(abilities[0].active,'Success also leaves wind active')
abilities=abilities.map(a=>({...a,targets:a.targets.filter(t=>t.id!==2)}))
combat={activeId:2,round:3};abilities=beginWindTurn(abilities,combat)
assert.equal(pendingWindSaves(abilities,combat).length,0,'Leaving before the turn prevents the save')
abilities=abilities.map(a=>({...a,targets:[...a.targets,{id:2,damage:'0',resolved:true}]}))
assert.equal(pendingWindSaves(abilities,combat).length,0,'Entering after turn start is not retroactive')
combat={activeId:2,round:4};abilities=beginWindTurn(abilities,combat)
assert.equal(pendingWindSaves(abilities,combat).length,1)
const second={...structuredClone(wind),id:9,ownerId:3,windSave:{dc:14}}
abilities=beginWindTurn([...abilities,second],combat)
assert.equal(pendingWindSaves(abilities,combat).length,2,'Independent casters retain independent saves and DCs')
abilities=resolveWindSave(abilities,combat,8,true)
assert.equal(pendingWindSaves(abilities,combat).length,1)
abilities=abilities.map(a=>({...a,active:false}))
assert.equal(pendingWindSaves(abilities,combat).length,0,'Ending effects or concentration clears their prompts')
assert.equal(windSaveResults(abilities,combat).length,0)
const forced=beginWindTurn([resolveWindSave(beginWindTurn([wind],{activeId:2,round:1}),{activeId:2,round:1},8,true)[0]],{activeId:2,round:1},true)
assert.equal(pendingWindSaves(forced,{activeId:2,round:1}).length,1,'Starting a new combat resets old start-turn receipts')
assert(validWindSave(forced[0].windSave))
for(const state of [null,[],{dc:'19'},{turn:{targetId:2,round:0,inLine:true}},{turn:{targetId:2,round:1,inLine:false,success:true}},{extra:true}])assert(!validWindSave(state))
const turns=[1,2,3].map(id=>({id,description:'Creatura '+id,initiative:'10',hitPoints:'30',armorClass:'12',temporaryHitPoints:''}))
assert.doesNotThrow(()=>validateState({turns,abilities:forced,combat:{activeId:2,round:1}}))
assert.throws(()=>validateState({turns,abilities:[{...forced[0],ruleId:'custom'}],combat:{activeId:2,round:1}}),e=>e.status===400)
console.log('PASS Wind turn timing: start snapshot, no entry/cast/redirect save, repeated turns, outcomes/reload, multiple casters, expiry, schema validation')

// Conditions are sampled at turn start; waking later never rerolls the already failed save.
for(const condition of ['unconscious','paralyzed','stunned','petrified']) {
 const status={id:20,name:condition==='unconscious'?'Sonno':'Condizione',...(condition==='unconscious'?{ruleId:'phb2014:spell:sleep'}:{}),ownerId:3,active:true,duration:'1 minuto',remainingTurns:10,targets:[{id:2,damage:'0',resolved:true}],resolutionEffects:[{kind:'condition',condition,trigger:'always'}]}
 const start={activeId:2,round:5},failed=beginWindTurn([wind,status],start)
 assert.equal(pendingWindSaves(failed,start).length,0)
 assert.equal(windSaveResults(failed,start)[0].windSave.turn.success,false)
 assert(failed[0].windSave.turn.automaticFailure)
 assert(validWindSave(failed[0].windSave))
 assert.doesNotThrow(()=>validateState({turns,abilities:failed,combat:start}))
 const awake=failed.filter(a=>a.id!==20)
 assert.deepEqual(beginWindTurn(awake,start),awake,'Waking in the same turn does not reopen the save')
 assert.equal(pendingWindSaves(beginWindTurn(awake,{...start,round:6}),{...start,round:6}).length,1,'Awake on the next turn: roll normally')
 const pending=beginWindTurn([wind],start)
 const oldPending=pending.map(a=>({...a,windSave:{...a.windSave,turn:{targetId:2,round:5,inLine:true}}}))
 const legacy=resolveAutomaticWindSaves([...oldPending,status],start)
 assert.equal(legacy[0].windSave.turn.success,false,'Old unresolved prompts are upgraded when opening the tracker')
 assert.deepEqual(beginWindTurn([...pending,status],start),[...pending,status],'A condition acquired after turn start does not change its snapshot')
 assert.deepEqual(resolveAutomaticWindSaves([...pending,status],start),[...pending,status],'Reloading cannot turn a later condition into a start-turn automatic failure')
}
assert(!validWindSave({turn:{targetId:2,round:1,inLine:true,success:true,automaticFailure:'Sonno'}}))
assert(!validWindSave({turn:{targetId:2,round:1,inLine:true,success:false,automaticFailure:23}}))
console.log('PASS Wind automatic failures: unconscious, paralyzed, stunned, petrified, legacy prompts, waking before/after start and validation')
